import pytest
from core.resolution.normalizer import clean_text


class TestNormalizer:

    @pytest.mark.parametrize("input_text, expected", [
        # 1. Базове переведення в нижній регістр
        ("МОЛОКО", "молоко"),
        ("Сир Твердий", "сир твердий"),
        ("kefir", "kefir"),

        # 2. Видалення знаків пунктуації та спецсимволів
        ("Шоколад Milka!", "шоколад milka"),
        ("Молоко, Яготинське", "молоко яготинське"),
        ("Печиво (з горіхами)", "печиво горіхами"),
        ("Сир «Голландський»", "сир голландський"),
        ("Ціна: 100$", "ціна 100"),
        ("Кефір 2.5%", "кефір 2 5"),  # Крапка і % замінюються на пробіли
        ("Кока-кола", "кока кола"),

        # 3. Нормалізація пробілів (зайві пробіли, таби, перенесення рядка)
        ("Сир    Твердий", "сир твердий"),
        ("Йогурт\tПерсиковий", "йогурт персиковий"),
        ("Банан \n 1 \n кг", "банан 1"),
        ("  Хліб   ", "хліб"),

        # 4. Видалення стоп-слів (акція, знижка, суперціна, новинка, упаковка, грн, шт, г, кг, мл, л)
        ("Акція Банан", "банан"),
        ("знижка Хліб білий", "хліб білий"),
        ("суперціна! Ковбаса", "ковбаса"),
        ("Новинка Йогурт", "йогурт"),
        ("Чай чорний упаковка", "чай чорний"),
        ("Ціна 50 грн", "ціна 50"),
        ("Яйця 10 шт", "яйця 10"),
        ("Сир 200 г", "сир 200"),
        ("М'ясо 1 кг", "м ясо 1"),  # Зверни увагу: апостроф ' видаляється і стає пробілом
        ("Сік 500 мл", "сік 500"),
        ("Вода 1.5 л", "вода 1 5"),

        # 5. Комбінація кількох стоп-слів та пунктуації
        ("Акція! Цукерки 500 г, суперціна 100 грн", "цукерки 500 100"),
        ("Новинка: Печиво 10 шт (упаковка)", "печиво 10"),
        ("Знижка - молоко 1 л 30 грн!", "молоко 1 30"),

        # 6. Захист від часткового збігу (False Positives)
        # Функція НЕ повинна видаляти букви всередині слів
        ("Штора", "штора"),  # містить 'шт', але це інше слово
        ("Гранат", "гранат"),  # містить 'г'
        ("Амлу", "амлу"),  # містить 'мл'
        ("КГБ", "кгб"),  # 'кг', але це частина іншого (або злите слово)
        ("Лілія", "лілія"),  # 'л' на початку
    ])
    def test_clean_text_variations(self, input_text, expected):
        """Параметризований тест, що проганяє десятки комбінацій рядків"""
        assert clean_text(input_text) == expected

    # 7. Тестування порожніх або None значень
    @pytest.mark.parametrize("invalid_input, expected", [
        ("", ""),
        (None, ""),
        ("   ", ""),  # Рядок тільки з пробілів
    ])
    def test_clean_text_empty_and_none(self, invalid_input, expected):
        """Перевірка, як нормалізатор справляється з порожніми даними"""
        assert clean_text(invalid_input) == expected

    # 8. Специфічні (екстремальні) випадки
    def test_clean_text_only_stop_words(self):
        """Якщо рядок складається лише зі стоп-слів та пунктуації, має повернутися порожній рядок"""
        assert clean_text("Акція! Знижка 100 грн за 1 кг (упаковка шт)") == "100 1"  # залишаться тільки цифри
        assert clean_text("акція знижка суперціна шт г кг") == ""

    def test_clean_text_numbers_only(self):
        """Цифри повинні залишатися недоторканими"""
        assert clean_text("12345") == "12345"
        assert clean_text("100 500") == "100 500"

    def test_clean_text_emojis_and_symbols(self):
        """Перевіряє, чи регулярний вираз успішно видаляє емодзі та нестандартні символи"""
        assert clean_text("Молоко 🥛 1 л 💯") == "молоко 1"
        assert clean_text("Банан 🍌🍌🍌 суперціна!!!") == "банан"

    def test_clean_text_wrong_type(self):
        """Перевіряє, чи програма очікувано 'свариться' помилкою AttributeError, якщо передати не рядок"""
        with pytest.raises(AttributeError):
            clean_text(123)  # Число (int) не має методу .lower()

        with pytest.raises(AttributeError):
            clean_text(
                ["Хліб", "Білий"])  # Список (list) не має методу .lower()def test_clean_text_emojis_and_symbols(self):
        """Перевіряє, чи регулярний вираз успішно видаляє емодзі та нестандартні символи"""
        assert clean_text("Молоко 🥛 1 л 💯") == "молоко 1"
        assert clean_text("Банан 🍌🍌🍌 суперціна!!!") == "банан"

